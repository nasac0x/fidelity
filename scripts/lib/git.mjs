// lib/git.mjs — per-project git so a bad fix cycle is one command to undo.
// Everything runs with `git -C <dir>`; nothing here touches the network.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const run = (dir, args) => spawnSync('git', ['-C', dir, ...args], { encoding: 'utf8' });

export const gitAvailable = () => spawnSync('git', ['--version'], { encoding: 'utf8' }).status === 0;
export const isRepo = (dir) => run(dir, ['rev-parse', '--is-inside-work-tree']).stdout.trim() === 'true';

const GITIGNORE = `# generated by fidelity
node_modules/
dist/
report/
visual-report/
budgets/
import/
judge/*.png
*.log
.DS_Store
`;

/** A fresh machine often has no git identity; set a local one instead of failing the commit. */
function ensureIdentity(dir) {
  if (!run(dir, ['config', 'user.email']).stdout.trim()) run(dir, ['config', 'user.email', 'fidelity@local']);
  if (!run(dir, ['config', 'user.name']).stdout.trim()) run(dir, ['config', 'user.name', 'fidelity']);
}

export function commitAll(dir, message) {
  run(dir, ['add', '-A']);
  const staged = run(dir, ['diff', '--cached', '--name-only']).stdout.trim();
  if (!staged) return { skipped: 'clean', files: 0 };
  const r = run(dir, ['commit', '-q', '-m', message]);
  if (r.status !== 0) return { error: r.stderr.trim().slice(0, 300) || r.stdout.trim().slice(0, 300) };
  return {
    commit: run(dir, ['rev-parse', '--short', 'HEAD']).stdout.trim(),
    files: staged.split('\n').filter(Boolean).length,
    message,
  };
}

export function init(dir, { commitMessage = 'chore: initial' } = {}) {
  if (!gitAvailable()) return { ok: false, reason: 'git not installed' };
  if (!fs.existsSync(dir)) return { ok: false, reason: `no such directory: ${dir}` };
  const created = !isRepo(dir);
  if (created) {
    const r = run(dir, ['init', '-q']);
    if (r.status !== 0) return { ok: false, reason: r.stderr.trim().slice(0, 200) };
    run(dir, ['symbolic-ref', 'HEAD', 'refs/heads/main']);
  }
  const gi = path.join(dir, '.gitignore');
  if (!fs.existsSync(gi)) fs.writeFileSync(gi, GITIGNORE);
  ensureIdentity(dir);
  return { ok: true, created, ...commitAll(dir, commitMessage) };
}

/** Commit the current tree and tag it, so the tag survives even if later commits exist. */
export function checkpoint(dir, name) {
  if (!isRepo(dir)) return { error: 'not a git repo — run project.mjs init first' };
  const commit = commitAll(dir, `checkpoint: ${name}`);
  const tag = `fidelity/${String(name).replace(/[^\w.-]+/g, '-')}`;
  if (run(dir, ['tag', '-l', tag]).stdout.trim()) return { ...commit, tag, note: 'tag already exists' };
  const r = run(dir, ['tag', tag]);
  return { ...commit, tag, tagged: r.status === 0 };
}

export function rollback(dir, ref) {
  if (!isRepo(dir)) return { ok: false, reason: 'not a git repo' };
  const has = run(dir, ['rev-parse', '--verify', '--quiet', ref]);
  if (has.status !== 0) return { ok: false, reason: `unknown ref: ${ref}` };
  const r = run(dir, ['reset', '--hard', ref]);
  if (r.status !== 0) return { ok: false, reason: r.stderr.trim().slice(0, 300) };
  return { ok: true, ref, head: run(dir, ['rev-parse', '--short', 'HEAD']).stdout.trim() };
}

export function status(dir) {
  if (!isRepo(dir)) return { ok: false, reason: 'not a git repo' };
  const head = run(dir, ['rev-parse', '--short', 'HEAD']);
  return {
    ok: true,
    head: head.status === 0 ? head.stdout.trim() : '(no commits)',
    branch: run(dir, ['branch', '--show-current']).stdout.trim() || '(detached)',
    dirty: run(dir, ['status', '--porcelain']).stdout.trim().split('\n').filter(Boolean).length,
    last: run(dir, ['log', '-1', '--pretty=%s']).stdout.trim(),
    tags: run(dir, ['tag', '-l', 'fidelity/*']).stdout.trim().split('\n').filter(Boolean),
  };
}
